package com.snaptube.clone.core.model

import kotlinx.serialization.Serializable

/** Extracted metadata about a media resource before download. */
@Serializable
data class MediaInfo(
    val id: String,
    val title: String,
    val uploader: String = "",
    val description: String = "",
    val durationMs: Long = 0L,
    val thumbnailUrl: String = "",
    val webpageUrl: String,
    val source: String = "",
    val viewCount: Long = 0L,
    val uploadDate: String = "",
    val formats: List<DownloadFormat> = emptyList(),
    val subtitles: List<SubtitleTrack> = emptyList(),
    val isLive: Boolean = false,
    /** True when the item cannot be downloaded (DRM, geo block, age gate, ...). */
    val isRestricted: Boolean = false,
    val restrictionReason: String = ""
) {
    val videoFormats: List<DownloadFormat> get() = formats.filter { it.mediaType == MediaType.VIDEO }
    val audioFormats: List<DownloadFormat> get() = formats.filter { it.mediaType == MediaType.AUDIO }
}

@Serializable
data class SubtitleTrack(
    val language: String,
    val label: String,
    val url: String,
    val isAutoGenerated: Boolean = false,
    val ext: String = "vtt"
)

/** Grouping of search/browse results returned by an extractor backend. */
@Serializable
data class SearchPage(
    val items: List<MediaInfo>,
    val nextPageToken: String? = null
)
